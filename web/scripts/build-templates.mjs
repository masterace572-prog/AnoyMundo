// Bundles the Handlebars templates into a plain JS module.
// Vercel's Node bundler traces static imports, so embedding the templates as
// string constants guarantees they are present inside the serverless function.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const viewsDir = path.join(root, 'views');
const outFile = path.join(root, 'src', 'templates.generated.mjs');

const templates = {};
for (const file of fs.readdirSync(viewsDir).filter((f) => f.endsWith('.hbs')).sort()) {
  templates[file.slice(0, -4)] = fs.readFileSync(path.join(viewsDir, file), 'utf8');
}

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(
  outFile,
  '// AUTO-GENERATED by scripts/build-templates.mjs - do not edit.\n' +
    'export const templates = ' + JSON.stringify(templates) + ';\n',
);
console.log(`[build-templates] bundled ${Object.keys(templates).length} templates -> src/templates.generated.mjs`);
