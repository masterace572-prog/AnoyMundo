// Bundles the line icons the panel uses into src/icons.generated.mjs.
// 2.3.3: the few icons app-ui.js draws in the browser (toasts, table rows,
// copy buttons) also go into a static SVG sprite with a content-hashed name,
// public/assets/icons/ui-<hash>.svg, cached for a year (vercel.json). Its
// path is exported as `uiSprite`; layout.hbs hands it to app-ui.js.
// Source: lucide-static (ISC licence, devDependency). Only the inner SVG
// markup is kept; render.mjs wraps it in one consistent <svg> element, so the
// icons ship inline with the HTML (no sprite request, no icon font, no CDN).
//   node scripts/build-icons.mjs
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const outFile = path.join(root, 'src', 'icons.generated.mjs');

export const ICONS = [
  'activity', 'arrow-right', 'at-sign', 'badge-check', 'ban', 'book-open', 'braces', 'calendar',
  'check', 'chevron-left', 'chevron-right', 'circle-alert', 'circle-check', 'clipboard-paste',
  'clock', 'cloud-upload', 'code-xml', 'copy', 'crown', 'download', 'ellipsis', 'external-link',
  'eye', 'eye-off', 'file-archive', 'gamepad-2', 'hash', 'hourglass', 'id-card', 'infinity', 'info',
  'key-round', 'key-square', 'layers', 'layout-dashboard', 'link', 'list-filter', 'lock', 'log-out',
  'mail', 'menu', 'minus', 'package', 'pencil', 'plug-zap', 'plus', 'power', 'refresh-cw', 'rotate-ccw',
  'search', 'send', 'server', 'settings', 'shield', 'shield-check', 'smartphone', 'sparkles', 'tag',
  'square-terminal', 'ticket', 'trash-2', 'triangle-alert', 'upload', 'user', 'user-plus',
  'user-round', 'users', 'wallet', 'wand-sparkles', 'wrench', 'x', 'zap',
  // 2.2.0: App update page.
  'circle-arrow-up', 'file-text', 'history', 'smartphone-nfc',
  // 2.3.4: keys list states / offline toast.
  'wifi-off',
];

let iconDir;
try {
  iconDir = path.join(path.dirname(require.resolve('lucide-static/package.json')), 'icons');
} catch {
  console.log('[build-icons] lucide-static not installed; keeping the committed icons.generated.mjs');
  process.exit(0);
}

// Icons app-ui.js uses (formerly an inline <template> in every page).
export const CLIENT_ICONS = [
  'copy', 'check', 'pencil', 'rotate-ccw', 'trash-2', 'x', 'circle-check', 'circle-alert',
  'triangle-alert', 'key-round', 'search', 'send',
  // 2.3.4: row "⋯" sheet, bulk select, keys states, offline toast.
  'ellipsis', 'plus', 'wifi-off',
];

const icons = {};
for (const name of ICONS) {
  const svg = fs.readFileSync(path.join(iconDir, `${name}.svg`), 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s+\/>/g, '/>')
    .trim();
  if (!inner) throw new Error(`empty icon ${name}`);
  icons[name] = inner;
}
const sprite = '<svg xmlns="http://www.w3.org/2000/svg">' +
  CLIENT_ICONS.map((name) => {
    if (!icons[name]) throw new Error(`client icon ${name} is not in ICONS`);
    return `<symbol id="${name}" viewBox="0 0 24 24">${icons[name]}</symbol>`;
  }).join('') + '</svg>\n';
const spriteHash = crypto.createHash('sha256').update(sprite).digest('hex').slice(0, 10);
const spriteDir = path.join(root, 'public', 'assets', 'icons');
fs.mkdirSync(spriteDir, { recursive: true });
for (const old of fs.readdirSync(spriteDir)) {
  if (/^ui-[0-9a-f]+\.svg$/.test(old) && old !== `ui-${spriteHash}.svg`) fs.unlinkSync(path.join(spriteDir, old));
}
fs.writeFileSync(path.join(spriteDir, `ui-${spriteHash}.svg`), sprite);

fs.writeFileSync(outFile,
  '// AUTO-GENERATED by scripts/build-icons.mjs from lucide-static (ISC licence). Do not edit.\n' +
  'export const icons = ' + JSON.stringify(icons, null, 0) + ';\n' +
  `export const uiSprite = '/assets/icons/ui-${spriteHash}.svg';\n`);
console.log(`[build-icons] ${Object.keys(icons).length} icons -> src/icons.generated.mjs`);
