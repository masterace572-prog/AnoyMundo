// Bundles the line icons the panel uses into src/icons.generated.mjs.
// Source: lucide-static (ISC licence, devDependency). Only the inner SVG
// markup is kept; render.mjs wraps it in one consistent <svg> element, so the
// icons ship inline with the HTML (no sprite request, no icon font, no CDN).
//   node scripts/build-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const outFile = path.join(root, 'src', 'icons.generated.mjs');

export const ICONS = [
  'activity', 'arrow-right', 'at-sign', 'badge-check', 'ban', 'book-open', 'braces', 'calendar',
  'check', 'chevron-left', 'chevron-right', 'circle-alert', 'circle-check', 'clipboard-paste',
  'clock', 'cloud-upload', 'code-xml', 'copy', 'crown', 'download', 'ellipsis', 'external-link',
  'eye', 'eye-off', 'file-archive', 'gamepad-2', 'hash', 'hourglass', 'id-card', 'infinity', 'info',
  'key-round', 'key-square', 'layers', 'layout-dashboard', 'link', 'list-filter', 'lock', 'log-out',
  'mail', 'menu', 'minus', 'package', 'pencil', 'plug-zap', 'plus', 'power', 'refresh-cw', 'rotate-ccw',
  'search', 'send', 'server', 'settings', 'shield', 'shield-check', 'smartphone', 'sparkles', 'tag',
  'square-terminal', 'ticket', 'trash-2', 'triangle-alert', 'upload', 'user', 'user-plus',
  'user-round', 'users', 'wallet', 'wand-sparkles', 'wrench', 'x', 'zap',
];

let iconDir;
try {
  iconDir = path.join(path.dirname(require.resolve('lucide-static/package.json')), 'icons');
} catch {
  console.log('[build-icons] lucide-static not installed; keeping the committed icons.generated.mjs');
  process.exit(0);
}

const icons = {};
for (const name of ICONS) {
  const svg = fs.readFileSync(path.join(iconDir, `${name}.svg`), 'utf8');
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/\s+\/>/g, '/>')
    .trim();
  if (!inner) throw new Error(`empty icon ${name}`);
  icons[name] = inner;
}
fs.writeFileSync(outFile,
  '// AUTO-GENERATED by scripts/build-icons.mjs from lucide-static (ISC licence). Do not edit.\n' +
  'export const icons = ' + JSON.stringify(icons, null, 0) + ';\n');
console.log(`[build-icons] ${Object.keys(icons).length} icons -> src/icons.generated.mjs`);
