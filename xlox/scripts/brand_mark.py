#!/usr/bin/env python3
"""The Anoy monogram: one geometry for the launcher icon, the system splash
icon and the splash Lottie (lottie_art.py imports it).

    python3 xlox/scripts/brand_mark.py      # writes the vector drawables

The mark is a geometric "A": a flat-topped white frame whose crossbar is a
#0A84FF bar that runs through the right leg and out past it, cut parallel to
the leg. Coordinates are in the 108-unit adaptive-icon canvas; the glyph sits
inside the 66-unit safe zone, so circle / squircle / rounded-square masks
never clip it.

Files written (all generated - edit this script, not the XML):
  res/drawable/ic_launcher_glyph.xml   adaptive foreground (108 canvas)
  res/drawable/ic_launcher_mark.xml    legacy glyph (the visible 72-unit window)
  res/drawable/splash_mark.xml         system splash icon = frame 0 of anoy_mark.json
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "app/src/main/res"

# White frame: flat apex, legs with horizontal feet, open counter.
FRAME = [(46.5, 33), (57.5, 33), (72, 75), (62.6, 75), (52, 43.5), (41.4, 75), (32, 75)]
# Blue crossbar. Left end follows the inner edge of the left leg (0.3 overlap
# so no anti-aliasing seam); right end is cut parallel to the right leg.
BAR = [(46.48, 59), (76, 59), (78.07, 65), (44.47, 65)]
# Inner crossbar: the same band clipped to the counter (inner leg edges). The
# system splash shows it in white so the letter reads as "A" from the first
# frame; the blue bar then draws over it and on past the right leg.
INNER_BAR = [(46.48, 59), (57.62, 59), (59.65, 65), (44.47, 65)]
CENTRE = (54, 54)

# The splash draws the mark at 2x in a 288 canvas. Frame 0 (and the system
# splash) shows a plain white A (frame + inner crossbar) at 96 %; the Lottie
# then draws the blue bar through it and settles to 100 %.
SPLASH_CANVAS = 288
SPLASH_SCALE = 2.0
SPLASH_START_SCALE = 0.96


def to_splash(points, scale=SPLASH_SCALE, centre=SPLASH_CANVAS / 2):
    """Glyph units -> splash canvas units around the canvas centre."""
    return [(centre + scale * (x - CENTRE[0]), centre + scale * (y - CENTRE[1])) for x, y in points]


def relative(points, scale=SPLASH_SCALE):
    """Glyph units -> coordinates around (0, 0) for a Lottie layer."""
    return [(scale * (x - CENTRE[0]), scale * (y - CENTRE[1])) for x, y in points]


def path_data(points):
    def f(v):
        s = f"{v:.2f}".rstrip("0").rstrip(".")
        return s if s else "0"
    head, *rest = points
    return "M" + f(head[0]) + "," + f(head[1]) + "".join(f"L{f(x)},{f(y)}" for x, y in rest) + "Z"


HEADER = '<?xml version="1.0" encoding="utf-8"?>\n'
GENERATED = "Generated by xlox/scripts/brand_mark.py - edit the script, not this file."


def vector(comment, size, viewport, body):
    return (HEADER + f"<!-- {comment}\n     {GENERATED} -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{size}dp"\n    android:height="{size}dp"\n'
            f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
            f"{body}</vector>\n")


def paths(frame, bar=None, indent="    ", inner=None):
    out = f'{indent}<path\n{indent}    android:fillColor="@color/white"\n{indent}    android:pathData="{path_data(frame)}" />\n'
    if inner:
        out += f'{indent}<path\n{indent}    android:fillColor="@color/white"\n{indent}    android:pathData="{path_data(inner)}" />\n'
    if bar:
        out += f'{indent}<path\n{indent}    android:fillColor="@color/blue"\n{indent}    android:pathData="{path_data(bar)}" />\n'
    return out


def write() -> None:
    files = {
        "drawable/ic_launcher_glyph.xml": vector(
            "Anoy monogram, adaptive-icon foreground (108 canvas, glyph inside the 66 safe zone).",
            108, 108, paths(FRAME, BAR)),
        # Legacy icons have no mask margin: show the same 72-unit window the
        # adaptive icon shows, so the glyph has the same proportions.
        "drawable/ic_launcher_mark.xml": vector(
            "Anoy monogram for the legacy (API 21-25) launcher icon: the visible 72-unit window.",
            48, 72, '    <group android:translateX="-18" android:translateY="-18">\n'
            + paths(FRAME, BAR, indent="        ") + "    </group>\n"),
        "drawable/splash_mark.xml": vector(
            "System splash icon = frame 0 of res/raw/anoy_mark.json: a plain white A at 96 %,\n"
            "     centred in the 288 dp splash canvas, so the hand-off to SplashActivity is seamless.",
            SPLASH_CANVAS, SPLASH_CANVAS,
            paths(to_splash(FRAME, SPLASH_SCALE * SPLASH_START_SCALE),
                  inner=to_splash(INNER_BAR, SPLASH_SCALE * SPLASH_START_SCALE))),
    }
    for rel, text in files.items():
        (RES / rel).write_text(text)
        print(f"[brand-mark] {rel}")


if __name__ == "__main__":
    write()
