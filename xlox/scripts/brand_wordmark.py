#!/usr/bin/env python3
"""The Anoy wordmark: the app icon and the system-splash icon.

    python3 xlox/scripts/brand_wordmark.py            # writes the vector drawables
    python3 xlox/scripts/brand_wordmark.py --report   # numbers only, writes nothing

Single source of truth for the word "Anoy" drawn as outlines (no runtime text):

  res/drawable/ic_launcher_glyph.xml   adaptive-icon foreground (108 dp canvas)
  res/drawable/ic_launcher_mark.xml    legacy icon glyph (the visible 72 dp window)
  res/drawable/splash_mark.xml         Android 12+ / core-splashscreen icon (288 dp)

The outlines come from Inter 4.001 (the version the app ships in res/font),
instanced from the variable font in scripts/fonts/InterVariable-Anoy.ttf, a
5 KB subset holding only A, n, o, y (SIL OFL 1.1, see
app/src/main/assets/licenses/OFL-Inter.txt). Requires fonttools and
skia-pathops (pip install fonttools skia-pathops).

Micro-adjustments over plain Inter SemiBold:
  * Weight 660 (SemiBold is 600): a touch heavier so it stays crisp at 48 dp.
    Optical size 14 = the text cut the app uses everywhere else.
  * Tracking -2.5 % of the em; A-n tightened by a further 3.5 % because the A's
    open right side leaves a hole. n-o-y keep Inter's own (optical) spacing.
  * The y's hook is lifted 26 % along the y's own diagonal, tapered to zero at
    the crotch, so the descender is shorter without thinning the tail.
  * Placed on its optical centre - halfway between the ink centroid and the
    box centre horizontally, and the A-to-baseline band blended with the ink
    centroid vertically - then scaled until the farthest point touches a
    31 dp radius: 2 dp inside the 66 dp adaptive safe zone, so circle, squircle,
    rounded-square and teardrop masks never clip a letter.
"""
import os
import sys

from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.statisticsPen import StatisticsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.path.join(HERE, "fonts", "InterVariable-Anoy.ttf")
RES = os.path.join(HERE, "..", "app", "src", "main", "res")
GENERATED = "Generated by xlox/scripts/brand_wordmark.py - edit the script, not this file."

WORD = "Anoy"
WGHT, OPSZ = 660, 14
TRACKING = -0.025          # of the em, between every pair
KERN = {("A", "n"): -0.035}  # extra, of the em
DESCENDER_LIFT = 0.26      # fraction of the y's descender depth removed
SAFE_RADIUS = 31.0         # dp on the 108 dp canvas: 2 dp inside the 33 dp safe-zone radius
CENTRE = 54.0

# System splash: the same outlines at the size of the splash's 40 sp "Anoy"
# (Inter cap height 0.727 em) so the hand-off into the film keeps its scale.
SPLASH_CANVAS = 288.0
SPLASH_CAP_DP = 40 * 0.727


def _glyph_outlines():
    """Returns ([(glyph, recorded_ops, x_offset)], upm, cap_height) in font units."""
    font = instantiateVariableFont(TTFont(FONT), {"wght": WGHT, "opsz": OPSZ})
    upm = font["head"].unitsPerEm
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    out, x, prev = [], 0.0, None
    for ch in WORD:
        name = cmap[ord(ch)]
        if prev is not None:
            x += (TRACKING + KERN.get((prev, ch), 0.0)) * upm
        rec = RecordingPen()
        glyphs[name].draw(rec)
        ops = rec.value
        if ch == "y":
            ops = _lift_descender(ops)
        out.append((name, ops, x))
        x += glyphs[name].width
        prev = ch
    return out, upm, font["OS/2"].sCapHeight


def _lift_descender(ops):
    """Slides the y's hook up along the y's right diagonal.

    Points below the baseline move by lift(y) along the stroke direction, where
    lift ramps from 0 at the baseline to the full amount at TAPER units down and
    stays constant below it. The hook therefore moves rigidly (its thickness and
    shape are kept), the outer diagonal stays straight, and only the short
    stretch next to the crotch is eased.
    """
    pts = [p for _, args in ops for p in args]
    depth = -min(p[1] for p in pts)
    lift = depth * DESCENDER_LIFT
    taper = depth * 0.44
    # Right stroke direction: the outer edge from the top-right corner down to
    # where it meets the hook (the lowest point on the far right).
    top = max((p for p in pts if p[1] > 0), key=lambda p: (p[1], p[0]))
    foot = max((p for p in pts if p[1] < 0), key=lambda p: p[0])
    dx, dy = top[0] - foot[0], top[1] - foot[1]

    def move(p):
        x, y = p
        if y >= 0:
            return p
        a = lift * min(1.0, -y / taper)
        return (x + a * dx / dy, y + a)

    return [(op, tuple(move(p) for p in args)) for op, args in ops]


def _union(items):
    """Draws every glyph into one outline with overlaps removed (A's crossbar)."""
    import pathops

    path = pathops.Path()
    pen = path.getPen()
    for _, ops, x in items:
        tp = TransformPen(pen, (1, 0, 0, 1, x, 0))
        for op, args in ops:
            getattr(tp, op)(*args)
    path.simplify(fix_winding=True, keep_starting_points=False)
    return path


def _points(path, steps=12):
    """Outline points including curve samples (for the safe-zone fit)."""
    rec = RecordingPen()
    path.draw(rec)
    pts, cur = [], (0.0, 0.0)
    for op, args in rec.value:
        if op in ("moveTo", "lineTo"):
            cur = args[0]
            pts.append(cur)
        elif op == "qCurveTo":
            p0 = cur
            ctrl, end = args[:-1], args[-1]
            # Expand implied on-curve points.
            segs = []
            for i, c in enumerate(ctrl):
                if i + 1 < len(ctrl):
                    nxt = ((c[0] + ctrl[i + 1][0]) / 2, (c[1] + ctrl[i + 1][1]) / 2)
                else:
                    nxt = end
                segs.append((c, nxt))
            for c, e in segs:
                for k in range(1, steps + 1):
                    t = k / steps
                    pts.append(((1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * c[0] + t * t * e[0],
                                (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * c[1] + t * t * e[1]))
                p0 = e
            cur = end
        elif op == "curveTo":
            p0 = cur
            c1, c2, e = args
            for k in range(1, steps + 1):
                t = k / steps
                mt = 1 - t
                pts.append((mt ** 3 * p0[0] + 3 * mt * mt * t * c1[0] + 3 * mt * t * t * c2[0] + t ** 3 * e[0],
                            mt ** 3 * p0[1] + 3 * mt * mt * t * c1[1] + 3 * mt * t * t * c2[1] + t ** 3 * e[1]))
            cur = e
    return pts


def layout():
    """Returns the union outline and its placement on the 108 dp canvas."""
    items, upm, cap = _glyph_outlines()
    path = _union(items)
    pts = _points(path)
    xmin = min(p[0] for p in pts)
    xmax = max(p[0] for p in pts)
    stats = StatisticsPen()
    path.draw(stats)
    # Font units, y up. Optical centre:
    ox = 0.5 * (xmin + xmax) * 0.5 + 0.5 * stats.meanX
    oy = 0.5 * (cap / 2.0) + 0.5 * stats.meanY
    far = max(((x - ox) ** 2 + (y - oy) ** 2) ** 0.5 for x, y in pts)
    scale = SAFE_RADIUS / far
    return {"path": path, "upm": upm, "cap": cap, "ox": ox, "oy": oy, "scale": scale,
            "pts": pts, "xmin": xmin, "xmax": xmax,
            "ymin": min(p[1] for p in pts), "ymax": max(p[1] for p in pts)}


def path_data(lay, scale, cx, cy):
    """SVG/Android path data placed with the optical centre at (cx, cy), y down."""
    pen = SVGPathPen(None, ntos=lambda v: ("%.2f" % v).rstrip("0").rstrip("."))
    tp = TransformPen(pen, (scale, 0, 0, -scale, cx - lay["ox"] * scale, cy + lay["oy"] * scale))
    lay["path"].draw(tp)
    return pen.getCommands()


def vector(comment, size_dp, viewport, data, translate=0.0):
    group_open = group_close = ""
    indent = "    "
    if translate:
        group_open = '    <group\n        android:translateX="%g"\n        android:translateY="%g">\n' % (translate, translate)
        group_close = "    </group>\n"
        indent = "        "
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- %s\n     %s -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="%gdp"\n    android:height="%gdp"\n'
            '    android:viewportWidth="%g"\n    android:viewportHeight="%g">\n'
            "%s"
            "%s<path\n%s    android:fillColor=\"@color/white\"\n%s    android:pathData=\"%s\" />\n"
            "%s"
            "</vector>\n") % (comment, GENERATED, size_dp, size_dp, viewport, viewport,
                              group_open, indent, indent, indent, data, group_close)


def outputs():
    lay = layout()
    icon = path_data(lay, lay["scale"], CENTRE, CENTRE)
    splash_scale = SPLASH_CAP_DP / lay["cap"]
    splash = path_data(lay, splash_scale, SPLASH_CANVAS / 2, SPLASH_CANVAS / 2)
    return lay, splash_scale, {
        "drawable/ic_launcher_glyph.xml": vector(
            "Adaptive-icon foreground: the word Anoy in white (Inter outlines), centred\n"
            "     optically inside the 66 dp safe zone of the 108 dp canvas.",
            108, 108, icon),
        "drawable/ic_launcher_mark.xml": vector(
            "Legacy icon glyph: the visible 72 dp window of ic_launcher_glyph.",
            72, 72, icon, translate=-18),
        "drawable/splash_mark.xml": vector(
            "System splash icon (288 dp, no icon background): the same Anoy outlines as\n"
            "     the launcher icon, at the cap height of the splash film's 40 sp text.",
            SPLASH_CANVAS, SPLASH_CANVAS, splash),
    }


def report(lay, splash_scale):
    s = lay["scale"]
    w = (lay["xmax"] - lay["xmin"]) * s
    print("icon: scale %.5f dp/unit, word %.1f dp wide, cap %.1f dp, x-height %.1f dp on the 108 canvas"
          % (s, w, lay["cap"] * s, 1118 * s))
    print("      at 48 dp on screen: word %.1f dp wide, cap %.1f dp" % (w * 48 / 72, lay["cap"] * s * 48 / 72))
    far = max(((x - lay["ox"]) ** 2 + (y - lay["oy"]) ** 2) ** 0.5 for x, y in lay["pts"]) * s
    print("      farthest point %.2f dp from centre (safe zone 33)" % far)
    print("      descender %.1f dp below baseline" % (-lay["ymin"] * s))
    print("splash: scale %.5f, word %.1f dp wide, cap %.1f dp"
          % (splash_scale, (lay["xmax"] - lay["xmin"]) * splash_scale, lay["cap"] * splash_scale))


def main():
    lay, splash_scale, files = outputs()
    report(lay, splash_scale)
    if "--report" in sys.argv:
        return
    for rel, text in files.items():
        with open(os.path.join(RES, rel), "w") as fh:
            fh.write(text)
        print("wrote res/" + rel)


if __name__ == "__main__":
    main()
