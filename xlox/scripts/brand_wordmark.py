#!/usr/bin/env python3
"""Generate KennyPvt launcher/system-splash vector wordmarks from bundled Inter.

Requires fonttools (python3 -m pip install fonttools). No network/font download.
The original Anoy assets stay byte-for-byte unchanged. Output is committed so
Android builds need no Python font dependency. Re-run after changing the brand.
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = Path(__file__).resolve().parents[1]
FONT = TTFont(ROOT / 'app/src/main/res/font/inter_semibold.ttf')
GLYPHS = FONT.getGlyphSet()
CMAP = FONT.getBestCmap()
BRAND = 'KennyPvt'
OUT = ROOT / 'app/src/kenny/res/drawable'


def draw(pen, scale=1, x=0, baseline=0):
    advance = 0
    for char in BRAND:
        glyph = GLYPHS[CMAP[ord(char)]]
        transform = (scale, 0, 0, -scale, x + advance * scale, baseline)
        glyph.draw(TransformPen(pen, transform))
        advance += glyph.width


bounds = BoundsPen(GLYPHS)
draw(bounds)
x1, y1, x2, y2 = bounds.bounds


def vector(viewport, max_width, text_size=None):
    scale = min(max_width / (x2 - x1), text_size / FONT['head'].unitsPerEm if text_size else 100)
    pen = SVGPathPen(GLYPHS, ntos=lambda value: format(value, '.2f').rstrip('0').rstrip('.'))
    draw(pen, scale, viewport / 2 - (x1 + x2) * scale / 2, viewport / 2 - (y1 + y2) * scale / 2)
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- KennyPvt, bundled Inter SemiBold outlines. Generated by scripts/brand_wordmark.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{viewport}dp" android:height="{viewport}dp"
    android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">
    <path android:fillColor="@color/white" android:pathData="{pen.getCommands()}" />
</vector>
'''


OUT.mkdir(parents=True, exist_ok=True)
# The 108 dp adaptive layer's central 66 dp is mask-safe. Legacy is the same
# optical wordmark in its 72 dp window. The film uses the shorter 32 dp type
# in this flavor so the longer brand plus "Loader" fits a 320 dp phone.
(OUT / 'ic_launcher_glyph.xml').write_text(vector(108, 62), encoding='utf8')
(OUT / 'ic_launcher_mark.xml').write_text(vector(72, 62), encoding='utf8')
(OUT / 'splash_mark.xml').write_text(vector(288, 192, text_size=32), encoding='utf8')
print('Generated KennyPvt adaptive, legacy and system-splash wordmarks.')
