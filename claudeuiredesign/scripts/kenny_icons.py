#!/usr/bin/env python3
"""Prepare the supplied KennyPvt artwork; never redraw it or touch Anoy assets.

  python3 -m pip install -r scripts/icon-requirements.txt
  python3 scripts/kenny_icons.py              # regenerate committed resources
  python3 scripts/kenny_icons.py --check      # verify pixels, geometry and XML
  python3 scripts/kenny_icons.py --check --apk KennyPvt-loader.apk

Android 21-25 gets high-quality rounded-square / round icons. Android 26+
gets real adaptive icons: the system owns the final circle/squircle mask.
The photo fills the central 72 dp viewport of the 108 dp foreground, rather
than being enlarged/cropped from an edge-to-edge 108 dp photo. The 288 dp
system-splash image keeps its circular 184 dp badge inside Android 12's
192 dp mask-safe circle, matching the first SplashActivity frame.
"""
from __future__ import annotations

import argparse
import hashlib
from io import BytesIO
import os
from pathlib import Path
import re
import subprocess
import sys
from zipfile import ZipFile

from PIL import Image, ImageChops, ImageDraw, ImageOps

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'app/src/kenny/res'
SOURCE = ROOT / 'artwork/kenny-logo.jpg'
SOURCE_SHA256 = 'd83c2810a2279fd429640294659a47d1548835ed3d727c1b666a777dec0b182c'
DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
# Byte-for-byte original icons. Branding changes here must stay Kenny-only.
ANOY_ICONS = {
    'drawable/ic_launcher.xml': '623ccb6e2eca6b3f1d742c0a30d6f08d49450bf3d3ce037cc5202ad254e8cda5',
    'drawable-v26/ic_launcher.xml': '4c9207706d6821284efce75d2bfbdba61264bbed462edef50b67bd2b9c5492d9',
    'drawable/ic_launcher_mark.xml': '506798b00abb163623254e5b51bff046fc42648b0981f5998936c55093629910',
    'drawable/ic_launcher_glyph.xml': 'bc47352d6f85439a254d6b69defbc17a0f824cd84a7175f5c6740f8ede4de49d',
    'drawable/splash_mark.xml': 'f6f09b1cf131983979a8cdd0509fa1c44c4ea222c12541c1a40c1bb4bc4e7d97',
}

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n'
NOTICE = '<!-- Supplied KennyPvt artwork. Generated by scripts/kenny_icons.py. -->\n'

def bitmap(name: str) -> str:
    return HEADER + NOTICE + f'''<bitmap xmlns:android="http://schemas.android.com/apk/res/android"
    android:src="@drawable/{name}"
    android:gravity="fill"
    android:antialias="true"
    android:filter="true" />
'''

ADAPTIVE = HEADER + NOTICE + '''<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/black" />
    <foreground android:drawable="@drawable/ic_launcher_glyph" />
</adaptive-icon>
'''
XML = {
    'drawable/ic_launcher.xml': bitmap('kenny_launcher_legacy'),
    'drawable/ic_launcher_round.xml': bitmap('kenny_launcher_round'),
    # Also override the old helper names so a future shared reference cannot
    # accidentally show the inherited Anoy vectors in the Kenny flavor.
    'drawable/ic_launcher_glyph.xml': bitmap('kenny_launcher_foreground'),
    'drawable/ic_launcher_mark.xml': bitmap('kenny_launcher_legacy'),
    'drawable-v26/ic_launcher.xml': ADAPTIVE,
    'drawable-v26/ic_launcher_round.xml': ADAPTIVE,
    'drawable/splash_mark.xml': bitmap('kenny_splash_badge'),
}


def artwork() -> Image.Image:
    if hashlib.sha256(SOURCE.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError('The supplied source artwork changed; review it before regenerating icons.')
    with Image.open(SOURCE) as original:
        if original.size != (640, 640) or original.getexif():
            raise ValueError('Expected the supplied 640 px image, without embedded EXIF.')
        return ImageOps.exif_transpose(original).convert('RGBA')


def badge(image: Image.Image, size: int, *, circle: bool = False) -> Image.Image:
    """Resize the full supplied square, then antialias only its outer mask."""
    picture = image.resize((size, size), Image.Resampling.LANCZOS)
    # Supersample the mask to avoid jagged curves even in the 48 px icon.
    large = Image.new('L', (size * 4, size * 4), 0)
    draw = ImageDraw.Draw(large)
    bounds = (0, 0, size * 4 - 1, size * 4 - 1)
    if circle:
        draw.ellipse(bounds, fill=255)
    else:
        draw.rounded_rectangle(bounds, radius=round(size * 4 * 0.225), fill=255)
    picture.putalpha(large.resize((size, size), Image.Resampling.LANCZOS))
    # Clear invisible RGB values too; leave visible pixels in straight RGBA.
    clean = Image.new('RGBA', picture.size)
    clean.alpha_composite(picture)
    return clean


def framed(image: Image.Image, canvas_dp: int, badge_dp: int, scale: float, *, circle: bool = False) -> Image.Image:
    canvas_size, badge_size = round(canvas_dp * scale), round(badge_dp * scale)
    canvas = Image.new('RGBA', (canvas_size, canvas_size))
    offset = (canvas_size - badge_size) // 2
    canvas.alpha_composite(badge(image, badge_size, circle=circle), (offset, offset))
    return canvas


def resources(image: Image.Image) -> dict[Path, Image.Image]:
    images = {}
    for density, scale in DENSITIES.items():
        directory = RES / f'drawable-{density}'
        images[directory / 'kenny_launcher_legacy.png'] = badge(image, round(48 * scale))
        images[directory / 'kenny_launcher_round.png'] = badge(image, round(48 * scale), circle=True)
        images[directory / 'kenny_launcher_foreground.png'] = framed(image, 108, 72, scale)
        images[directory / 'kenny_splash_badge.png'] = framed(image, 288, 184, scale, circle=True)
    return images


def check_geometry(images: dict[Path, Image.Image]) -> None:
    for density, scale in DENSITIES.items():
        directory = RES / f'drawable-{density}'
        for name in ('kenny_launcher_legacy', 'kenny_launcher_round'):
            icon = images[directory / f'{name}.png']
            alpha = icon.getchannel('A')
            assert icon.size == (round(48 * scale),) * 2
            assert alpha.getpixel((0, 0)) == 0 and alpha.getpixel((icon.width // 2, icon.height // 2)) == 255
        foreground = images[directory / 'kenny_launcher_foreground.png']
        assert foreground.size == (round(108 * scale),) * 2
        assert foreground.getchannel('A').getbbox() == (round(18 * scale),) * 2 + (round(90 * scale),) * 2
        splash = images[directory / 'kenny_splash_badge.png']
        assert splash.size == (round(288 * scale),) * 2
        safe = Image.new('L', splash.size)
        ImageDraw.Draw(safe).ellipse((round(48 * scale), round(48 * scale), round(240 * scale), round(240 * scale)), fill=255)
        assert ImageChops.subtract(splash.getchannel('A'), safe).getbbox() is None, 'Splash artwork must stay inside Android 12 mask'
    for relative, digest in ANOY_ICONS.items():
        original = ROOT / 'app/src/main/res' / relative
        assert hashlib.sha256(original.read_bytes()).hexdigest() == digest, 'Anoy icon changed: ' + relative


def equal_pixels(actual: Image.Image, expected: Image.Image) -> bool:
    return actual.size == expected.size and actual.convert('RGBA').tobytes() == expected.tobytes()


def compiled_resources(path: Path) -> str:
    sdk = os.environ.get('ANDROID_SDK_ROOT') or os.environ.get('ANDROID_HOME')
    tools = sorted(Path(sdk).glob('build-tools/*/aapt2')) if sdk else []
    if not tools:
        raise ValueError('--apk requires aapt2 under ANDROID_SDK_ROOT/build-tools (source checks need no SDK)')
    result = subprocess.run([str(tools[-1]), 'dump', 'resources', str(path)], capture_output=True, text=True)
    if result.returncode:
        raise ValueError('aapt2 could not inspect APK resources: ' + result.stderr[:2000])
    return result.stdout


def packaged_images(dump: str) -> dict[tuple[str, str], list[str]]:
    """Resolve resource + density to file even when AGP shortens it to res/a.png."""
    files: dict[tuple[str, str], list[str]] = {}
    blocks = re.finditer(r'^\s*resource [^\n]*\bdrawable/(\w+)[^\n]*\n(.*?)(?=^\s*resource |\Z)', dump, re.M | re.S)
    density_aliases = {'160dpi': 'mdpi', '240dpi': 'hdpi', '320dpi': 'xhdpi', '480dpi': 'xxhdpi', '640dpi': 'xxxhdpi'}
    for block in blocks:
        for line in block[2].splitlines():
            match = re.match(r'^\s*\(([^)]*)\)\s*\(file\)\s+(?:"([^"]+)"|(\S+))', line)
            if not match:
                continue
            qualifiers = [density_aliases.get(part, part) for part in match[1].split('-')]
            for density in DENSITIES:
                if density in qualifiers:
                    files.setdefault((block[1], density), []).append(match[2] or match[3])
    return files


def check_apk(path: Path, expected: dict[Path, Image.Image], *, resource_dump: str | None = None) -> None:
    """Follow the compiled resource table, then compare decoded visible pixels."""
    files = packaged_images(compiled_resources(path) if resource_dump is None else resource_dump)
    with ZipFile(path) as apk:
        for source, image in expected.items():
            density = source.parent.name.removeprefix('drawable-')
            candidates = files.get((source.stem, density), [])
            assert len(candidates) == 1 and candidates[0] in apk.namelist(), 'Missing or ambiguous packaged icon: ' + str(source.relative_to(RES))
            with Image.open(BytesIO(apk.read(candidates[0]))) as decoded:
                actual = decoded.convert('RGBA')
                assert actual.size == image.size, 'Packaged icon density changed: ' + str(source.relative_to(RES))
                for colour in ('black', 'white'):
                    background = Image.new('RGBA', image.size, colour)
                    before = Image.alpha_composite(background, image).convert('RGB')
                    after = Image.alpha_composite(background, actual).convert('RGB')
                    difference = ImageChops.difference(before, after)
                    assert max(high for low, high in difference.getextrema()) <= 1, 'Packaged artwork changed: ' + str(source.relative_to(RES))
    print('PASS  Kenny APK contains the supplied artwork at all five densities (compiled resource table + decoded pixel check)')


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='verify without rewriting any files')
    parser.add_argument('--apk', type=Path, help='also inspect the compiled Kenny APK')
    args = parser.parse_args()
    image = artwork()
    images = resources(image)
    check_geometry(images)
    preview = ROOT / 'artwork/kenny-icon-preview.png'
    outputs = {**images, preview: badge(image, 512)}
    for path, expected in outputs.items():
        if args.check:
            with Image.open(path) as actual:
                assert equal_pixels(actual, expected), 'Stale artwork: ' + str(path.relative_to(ROOT))
                assert not actual.getexif(), 'Generated icons must not embed EXIF'
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            expected.save(path, optimize=True)
    for relative, text in XML.items():
        path = RES / relative
        if args.check:
            assert path.read_text() == text, 'Stale drawable: ' + relative
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print('PASS  supplied Kenny artwork, rounded / round / adaptive icons and mask-safe splash at all five densities')
    print('PASS  Anoy launcher and startup icon assets remain byte-for-byte unchanged')
    if args.apk:
        check_apk(args.apk, images)


if __name__ == '__main__':
    try:
        main()
    except (AssertionError, OSError, ValueError) as error:
        print('FAIL  ' + str(error), file=sys.stderr)
        if os.environ.get('GITHUB_ACTIONS'):
            message = str(error).replace('%', '%25').replace('\r', '%0D').replace('\n', '%0A')
            print('::error title=Kenny artwork verification::' + message)
        sys.exit(1)
